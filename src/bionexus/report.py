"""Self-contained HTML campaign report (shareable artifact).

`bn prove <branch> --html report.html` renders the provenance chain, chain
verification, hypothesis verdicts, and any artifacts (IND package, dossiers)
into one dark-blueprint HTML file with no external dependencies.
"""
from __future__ import annotations

import html as _html
import json
from pathlib import Path
from typing import Any

TEMPLATE = """<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>BioNexus Report — {branch}</title>
<style>
  :root {{ --bg:#f3f1ea; --grid:#e3ded2; --paper:#faf8f2; --line:#c9c2b0;
    --ink:#2a2823; --dim:#6b6558; --green:#2f6b38; --red:#8a4034; --amber:#8a6a2c;
    --mono:'IBM Plex Mono','SFMono-Regular',Consolas,monospace; }}
  * {{ box-sizing:border-box; }}
  body {{ margin:0; background:var(--bg); color:var(--ink);
    background-image:linear-gradient(var(--grid) 1px,transparent 1px),
    linear-gradient(90deg,var(--grid) 1px,transparent 1px); background-size:28px 28px;
    font-family:-apple-system,'Segoe UI',sans-serif; padding:40px 20px 80px; }}
  .wrap {{ max-width:980px; margin:0 auto; }}
  h1 {{ font-size:24px; margin:0 0 4px; letter-spacing:-0.01em; }}
  .eyebrow {{ font-family:var(--mono); font-size:11px; letter-spacing:.14em;
    text-transform:uppercase; color:var(--dim); margin-bottom:24px; }}
  table {{ width:100%; border-collapse:collapse; background:var(--paper);
    border:1px solid var(--line); font-size:13px; }}
  th,td {{ text-align:left; padding:8px 12px; border-bottom:1px solid var(--line); }}
  th {{ font-family:var(--mono); font-size:11px; letter-spacing:.06em;
    text-transform:uppercase; color:var(--dim); }}
  td.mono, code {{ font-family:var(--mono); font-size:12px; }}
  .ok {{ color:var(--green); font-weight:600; }}
  .bad {{ color:var(--red); font-weight:600; }}
  .section {{ margin-top:32px; }}
  pre {{ background:var(--paper); border:1px solid var(--line); padding:14px;
    font-family:var(--mono); font-size:12px; overflow-x:auto; }}
  .stats {{ display:flex; gap:14px; flex-wrap:wrap; margin-top:16px; }}
  .stat {{ background:var(--paper); border:1px solid var(--line); padding:12px 18px; }}
  .stat b {{ display:block; font-size:20px; }}
  .stat span {{ font-family:var(--mono); font-size:11px; color:var(--dim); }}
</style></head><body><div class="wrap">
  <p class="eyebrow">BioNexus · Campaign Report</p>
  <h1>Provenance — {branch}</h1>
  <div class="stats">{stats}</div>
  <div class="section"><table>
    <tr><th>#</th><th>Event</th><th>Detail</th><th>Hash</th><th>Chain</th></tr>
    {rows}
  </table></div>
  <div class="section"><pre>{artifacts}</pre></div>
  <p class="eyebrow" style="margin-top:32px">generated by bionexus · records hash-chained (sha256), hashes RECOMPUTED from content when this report was rendered · external integrity via a published `bn anchor` root</p>
</div></body></html>
"""


def build_report(records: list[Any]) -> str:
    from bionexus.adapters.store.sqlite import SqliteProvenanceStore
    prev_ok = True
    prev_hash = None
    edited = 0
    rows = []
    artifacts: list[dict[str, Any]] = []
    for i, r in enumerate(records, 1):
        hash_ok = SqliteProvenanceStore._hash(r) == (r.record_hash or "")
        if not hash_ok:
            edited += 1
        ok = (r.prev_record_hash == prev_hash) and hash_ok
        prev_ok &= ok
        detail = ""
        if r.decision:
            detail = _html.escape(json.dumps(r.decision)[:120])
        elif r.artifact:
            detail = _html.escape(f"{r.artifact.kind.value}: {r.artifact.artifact_id}")
        if r.artifact and r.artifact.metadata:
            artifacts.append(r.artifact.model_dump())
        rows.append(
            f"<tr><td class='mono'>{i}</td>"
            f"<td>{_html.escape(r.event_type.value)}</td>"
            f"<td class='mono'>{detail}</td>"
            f"<td class='mono'>{(r.record_hash or '')[:12]}…</td>"
            f"<td class='{'ok' if ok else 'bad'}'>"
            f"{'ok' if ok else ('EDITED' if not hash_ok else 'BROKEN')}"
            f"</td></tr>"
        )
        prev_hash = r.record_hash
    events = [r.event_type.value for r in records]
    stats = "".join(
        f"<div class='stat'><b>{v}</b><span>{k}</span></div>"
        for k, v in {
            "records": len(records),
            "hypotheses": sum(1 for e in events if e.startswith("hypothesis")),
            "validated": sum(1 for e in events if e == "hypothesis_validated"),
            "invalidated": sum(1 for e in events if e == "hypothesis_invalidated"),
            "inconclusive": sum(1 for e in events
                                if e == "hypothesis_inconclusive"),
            "gates": sum(1 for e in events if e == "gate_decision"),
            "lab runs": sum(1 for e in events if e == "lab_run"),
            "chain": ("intact (recomputed)" if prev_ok and not edited
                      else "BROKEN" if not prev_ok else "EDITED"),
        }.items()
    )
    return TEMPLATE.format(
        branch=_html.escape(records[0].envelope.experiment_branch_id if records else "?"),
        stats=stats,
        rows="\n".join(rows),
        artifacts=_html.escape(json.dumps(artifacts, indent=1)[:4000] or "{}"),
    )


def write_report(records: list[Any], path: str | Path) -> Path:
    p = Path(path)
    p.write_text(build_report(records))
    return p
