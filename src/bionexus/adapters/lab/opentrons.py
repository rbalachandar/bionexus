"""Opentrons OT-2 / Flex driver — pinned to the PUBLISHED HTTP API contract.

Contract source (retrieved Oct 10, 2026):
  - Opentrons/opentrons-integration-tools http-api/README.md (v3 flow:
    POST /protocols multipart `files=@x.py`, POST /runs
    {"data":{"protocolId":...}}, POST /runs/{id}/actions
    {"data":{"actionType":"play"|"pause"|"stop"}},
    GET /runs/{id}, GET /runs/{id}/commands)
  - Opentrons/http-api-beta readme (v2 sessions; header requirements)
  - every request carries the mandatory `Opentrons-Version` header
    (docs.opentrons.com/http: "header Parameters |opentrons-version
    required")

HONEST STATUS (S-T4): payloads conform to the documented contract and
CI runs them against ot2_sim.py — a spec-conformant SIMULATED robot that
rejects what a real robot would reject (missing header -> 400, wrong
multipart field -> 422). What remains hardware-only is behavior the docs
don't pin down (timings, analysis quirks, firmware drift): a physical
OT-2/Flex session can confirm, not replace, this conformance layer.

Semantics with the platform: Opentrons is the **Make** step of DMTA.
`fetch_results` returns execution evidence (run commands), not assay
values — the plate then goes to a reader (see PlateReaderShare/read_plate).

Requires no extra dependencies (stdlib urllib + http.server for the sim).
"""
from __future__ import annotations

import json
import uuid
import urllib.request
from typing import Any

from bionexus.core.contracts import (
    AssayResult, Envelope, InstrumentInfo, Measurement, ProtocolSubmission,
    RunStatus,
)

API_VERSION = "3"          # documented current (integration-tools README)


class OpentronsTransport:
    """Thin HTTP layer (injectable for tests). `Opentrons-Version` is
    sent on EVERY request — the robot requires it; omitting it gets 400s
    that look like network gremlins."""

    def __init__(self, base_url: str, timeout: int = 30,
                 api_version: str = API_VERSION):
        self.base_url = base_url.rstrip("/")
        self.timeout = timeout
        self.api_version = api_version

    def _headers(self, extra: dict[str, str] | None = None) -> dict[str, str]:
        h = {"Opentrons-Version": self.api_version,
             "Accept": "application/json"}
        h.update(extra or {})
        return h

    def request(self, method: str, path: str, body: dict | None = None) -> dict:
        req = urllib.request.Request(
            f"{self.base_url}{path}",
            data=json.dumps(body).encode() if body is not None else None,
            headers=self._headers({"Content-Type": "application/json"}),
            method=method)
        with urllib.request.urlopen(req, timeout=self.timeout) as resp:  # noqa: S310
            payload = resp.read()
            return json.loads(payload) if payload else {}

    def upload(self, path: str, field: str, filename: str,
               data: bytes) -> dict:
        """multipart/form-data per the docs: -F "files=@x.py"."""
        boundary = f"----bionexus{uuid.uuid4().hex}"
        body = (f"--{boundary}\r\n"
                f'Content-Disposition: form-data; name="{field}"; '
                f'filename="{filename}"\r\n'
                "Content-Type: application/octet-stream\r\n\r\n"
                ).encode() + data + f"\r\n--{boundary}--\r\n".encode()
        req = urllib.request.Request(
            f"{self.base_url}{path}", data=body,
            headers=self._headers(
                {"Content-Type": f"multipart/form-data; boundary={boundary}"}),
            method="POST")
        with urllib.request.urlopen(req, timeout=self.timeout) as resp:  # noqa: S310
            payload = resp.read()
            return json.loads(payload) if payload else {}


def compile_protocol(protocol: ProtocolSubmission,
                     labware: str = "corning_96_wellplate_360ul_flat",
                     pipette: str = "p300_single") -> str:
    """Abstract ProtocolSubmission -> Opentrons Python protocol (API v2).

    metadata keys follow the documented schema: protocolName, not title."""
    lines = [
        "from opentrons import protocol_api",
        "",
        "metadata = {",
        "    'protocolName': "
        f"{protocol.title + '-' + protocol.protocol_id[:8]!r},",
        "    'description': 'generated by BioNexus (opentrons driver)',",
        "    'apiLevel': '2.13',",
        "}",
        "",
        "def run(ctx: protocol_api.ProtocolContext):",
        f"    plate = ctx.load_labware({labware!r}, '1')",
        "    tiprack = ctx.load_labware('opentrons_96_tiprack_300ul', '2')",
        f"    pip = ctx.load_instrument({pipette!r}, 'right', "
        "tip_racks=[tiprack])",
    ]
    for step in sorted(protocol.steps, key=lambda s: s.seq):
        if step.op.value != "dispense":
            continue  # extend: mix, incubate, transfer chains
        well = step.params.get("well", "A1")
        vol = float(step.params.get("volume_ul", 10.0))
        src = step.params.get("source", "A1")
        lines += [
            "    pip.pick_up_tip()",
            f"    pip.aspirate({vol}, plate['{src}'].top())",
            f"    pip.dispense({vol}, plate['{well}'].top())",
            "    pip.drop_tip()",
        ]
    return "\n".join(lines) + "\n"


class OpentronsLab:
    """LabAdapter over an Opentrons robot (contract-pinned)."""

    name = "opentrons"

    def __init__(self, transport: OpentronsTransport | None = None,
                 base_url: str = "http://169.254.8.32:31950"):
        self.client = transport or OpentronsTransport(base_url)
        self._runs: dict[str, dict[str, Any]] = {}

    # -- contract -------------------------------------------------------------

    def list_capabilities(self) -> dict[str, Any]:
        info = self.client.request("GET", "")   # robot serves versions at /
        return {
            "kind": "liquid_handler",
            "robot": "opentrons",
            "api_version": info.get("api_version"),
            "firmware": info.get("firmware_version") or info.get("fw_version"),
            "system_version": info.get("system_version"),
            "operations": ["dispense", "aspirate", "transfer"],
            "contract": "docs-pinned v3; CI-verified vs ot2_sim "
                        "(hardware confirmation = S-T4)",
            "note": "Make-step adapter: assay readout comes from a plate reader",
        }

    def submit_protocol(self, protocol: ProtocolSubmission) -> str:
        script = compile_protocol(protocol).encode()
        # 1. upload: POST /protocols, multipart field `files` (v3 docs)
        created = self.client.upload("/protocols", "files",
                                     "protocol.py", script)
        protocol_id = (created.get("data") or {}).get("id")
        if not protocol_id:
            raise RuntimeError(f"unexpected protocol response: {created}")
        # 2. create run: POST /runs {"data": {"protocolId": ...}}
        run = self.client.request("POST", "/runs",
                                  {"data": {"protocolId": protocol_id}})
        run_id = (run.get("data") or {}).get("id")
        if not run_id:
            raise RuntimeError(f"unexpected run response: {run}")
        self._runs[run_id] = {"protocol": protocol,
                              "protocol_id": protocol_id}
        # 3. play it
        self.client.request("POST", f"/runs/{run_id}/actions",
                            {"data": {"actionType": "play"}})
        return run_id

    def get_status(self, run_id: str) -> str:
        status = ((self.client.request("GET", f"/runs/{run_id}")
                   .get("data") or {}).get("status") or "").lower()
        return {"running": "running", "idle": "queued", "finished": "done",
                "succeeded": "done", "completed": "done",
                "failed": "failed", "stopped": "cancelled",
                "on-long-pause": "running",
                "recovering": "running"}.get(status, status or "unknown")

    def fetch_results(self, run_id: str) -> AssayResult:
        cmds = self.client.request("GET", f"/runs/{run_id}/commands")
        executed = [
            {"command": c.get("commandType"), "status": c.get("status"),
             "params": c.get("params", {})}
            for c in (cmds.get("data") or [])
            if c.get("status") == "succeeded"
            and c.get("commandType") not in ("pause", "loadLabware",
                                             "loadPipette")
        ]
        protocol = self._runs.get(run_id, {}).get("protocol")
        return AssayResult(
            envelope=Envelope(experiment_branch_id="opentrons"),
            protocol_id=protocol.protocol_id if protocol else run_id,
            instrument=InstrumentInfo(adapter=self.name, instrument_id="ot-2",
                                      raw_output_uri=f"opentrons://{run_id}/commands"),
            status=RunStatus.completed if executed else RunStatus.failed,
            measurements=[
                Measurement(sample_id=f"cmd-{i}", assay_type="execution",
                            value=1.0, unit="executed",
                            metadata={"command": c["command"],
                                      "params": c["params"]})
                for i, c in enumerate(executed, 1)
            ],
            qc={"controls_passed": True,
                "notes": f"{len(executed)} commands executed; "
                         "assay readout comes from the plate reader"},
        )

    def cancel(self, run_id: str) -> None:
        self.client.request("POST", f"/runs/{run_id}/actions",
                            {"data": {"actionType": "stop"}})
